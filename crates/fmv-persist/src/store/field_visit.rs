pub const MAX_FIELD_VISIT_FIELD_BYTES: usize = 256;
pub const MAX_FIELD_VISIT_ENTRY_BYTES: usize = 1024;
pub const MAX_FIELD_VISIT_ANCHOR_BYTES: usize = 1024;
/// Compact visit JSON: two fixed 512-character scratch strings, at most 8 KiB for
/// the two opaque byte arrays (four JSON characters per byte), 1536 bytes for a fully
/// escaped field name (six per input byte), and under 2 KiB for fixed ids/keys/numbers.
/// The explicit cap leaves headroom while keeping every snapshot bounded independently.
pub const MAX_FIELD_VISIT_BYTES: usize = 16 * 1024;

/// The accepted entry, supplied only after the adapter validates its provenance. `arrival`
/// is a bounded canonical encoding of the authored transition and durable entry placement.
/// It is not reconstructed from a network acknowledgment or from an absent prior visit.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct FieldVisitEntryV1 {
    pub operation: [u8; 16],
    pub arrival: Vec<u8>,
}

/// Per-account, per-game field state with a lifetime independent of story progression.
/// Returning from a menu/battle or reconnecting retains it; an actual accepted field entry
/// uses a new id even when it returns to the same field. Ids must be freshly generated by
/// the caller, never derived from the field name. Unknown scratch bits must be zero.
///
/// `anchor` includes a reviewed reconstruction profile AND durable placement, not merely
/// coordinates. The game adapter validates both opaque encodings and source identity before
/// any gameplay. Storage alone does not authorize a VM resume. Native party data remains
/// inside the opaque story blob and is committed with the visit, never duplicated here.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct FieldVisitV1 {
    pub schema_version: u32,
    pub visit_id: [u8; 16],
    pub revision: u64,
    pub field: String,
    pub source_identity: [u8; 32],
    pub entry: FieldVisitEntryV1,
    pub anchor: Vec<u8>,
    #[serde(serialize_with = "crate::model::hex_blob::serialize", deserialize_with = "crate::model::hex_blob::deserialize_exact")]
    pub scratch_values: [u8; 256],
    #[serde(serialize_with = "crate::model::hex_blob::serialize", deserialize_with = "crate::model::hex_blob::deserialize_exact")]
    pub scratch_known_masks: [u8; 256],
    pub active_continuation: Option<[u8; 32]>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum FieldVisitOperationKind { Enter, Advance }

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct FieldVisitOperation {
    pub id: [u8; 16],
    pub kind: FieldVisitOperationKind,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct FieldVisitCommitted {
    pub commit: SceneCommit,
    /// A duplicate returns the current records, preserving any later rewards or saves.
    pub current: SceneState,
}

/// A single replaceable receipt, not a permanently growing history of field entries.
/// Its digest binds the exact supplied operation and complete expected/next SceneState,
/// including timestamps, caller schema, opaque story/resources and continuation metadata.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub(super) struct VisitReceipt {
    operation: [u8; 16],
    request: String,
}

impl VisitReceipt {
    pub(super) fn validate(&self) -> Result<()> {
        if self.operation == [0; 16] || !is_digest(&self.request) {
            return Err(invalid("invalid last visit receipt"));
        }
        Ok(())
    }
}

fn invalid(reason: &str) -> PersistError { PersistError::InvalidField { field: "field_visit", reason: reason.into() } }
fn conflict(reason: &str) -> PersistError { PersistError::TransactionConflict(reason.into()) }

impl FieldVisitV1 {
    pub(super) fn validate(&self) -> Result<()> {
        if self.schema_version != 1 || self.visit_id == [0; 16] || self.source_identity == [0; 32]
            || self.entry.operation == [0; 16] || self.active_continuation == Some([0; 32]) {
            return Err(invalid("invalid visit schema or identity"));
        }
        if self.field.is_empty() || self.field.len() > MAX_FIELD_VISIT_FIELD_BYTES || self.field.chars().any(char::is_control) {
            return Err(invalid("field name must be nonempty, bounded and have no control characters"));
        }
        if self.entry.arrival.is_empty() || self.entry.arrival.len() > MAX_FIELD_VISIT_ENTRY_BYTES
            || self.anchor.is_empty() || self.anchor.len() > MAX_FIELD_VISIT_ANCHOR_BYTES {
            return Err(invalid("entry and reconstruction anchor must be nonempty and bounded"));
        }
        if self.scratch_values.iter().zip(&self.scratch_known_masks).any(|(value, mask)| value & !mask != 0) {
            return Err(invalid("unknown scratch bits must be zero"));
        }
        let bytes = serde_json::to_vec(self).map_err(|e| invalid(&format!("cannot encode visit: {e}")))?;
        if bytes.len() > MAX_FIELD_VISIT_BYTES { return Err(invalid("encoded visit exceeds its size limit")); }
        Ok(())
    }
}

/// Existing batch operations preserve visits, so they cannot invent, change or orphan a
/// link. A future explicitly reviewed lifecycle operation must atomically update both.
/// Guests own independent visits; a guest reservation is not its own scene checkpoint.
pub(super) fn validate_link(visit: Option<&FieldVisitV1>, checkpoint: Option<&SceneCheckpoint>, _reservation: Option<&SceneReservation>) -> Result<()> {
    if let Some(visit) = visit {
        visit.validate()?;
        if visit.active_continuation != checkpoint.map(|checkpoint| checkpoint.instance) {
            return Err(invalid("visit continuation must exactly identify its owning checkpoint"));
        }
    }
    Ok(())
}

fn validate_transition(operation: &FieldVisitOperation, before: &SceneState, after: &SceneState) -> Result<()> {
    if operation.id == [0; 16] { return Err(invalid("visit operation identity must be nonzero")); }
    let (account, game) = (before.pair.story.account_id, before.pair.story.game);
    for state in [before, after] {
        state.pair.validate(account, game)?;
        if state.pair.character.is_none() { return Err(invalid("visit transaction requires stored character progress")); }
        validate_link(state.field_visit.as_ref(), state.checkpoint.as_ref(), state.reservation.as_ref())?;
        if state.checkpoint.is_some() || state.reservation.is_some()
            || state.field_visit.as_ref().is_some_and(|visit| visit.active_continuation.is_some()) {
            return Err(conflict("standalone visit changes require an idle account"));
        }
    }
    let next = after.field_visit.as_ref().ok_or_else(|| invalid("visit after-image is absent"))?;
    match operation.kind {
        FieldVisitOperationKind::Enter => {
            if next.revision != 0 || next.entry.operation != operation.id
                || before.field_visit.as_ref().is_some_and(|old| old.visit_id == next.visit_id) {
                return Err(invalid("entry requires a fresh visit identity, revision zero and its accepted entry operation"));
            }
        }
        FieldVisitOperationKind::Advance => {
            let old = before.field_visit.as_ref().ok_or_else(|| invalid("advance requires an existing visit"))?;
            if old.revision.checked_add(1) != Some(next.revision) || old.visit_id != next.visit_id
                || old.field != next.field || old.source_identity != next.source_identity || old.entry != next.entry {
                return Err(invalid("advance must retain entry identity and advance exactly one revision without wrapping"));
            }
            if old.scratch_known_masks.iter().zip(&next.scratch_known_masks).any(|(old, next)| old & !next != 0) {
                return Err(invalid("advance cannot forget known scratch bits; reset requires a new entry"));
            }
        }
    }
    Ok(())
}

pub(super) const VISIT_INTENT_VERSION: u32 = 3;
/// Compact before/after images contain two records each: at most 4 MiB character + 1 MiB
/// story per image. Compact JSON is no larger than the validated pretty record encodings.
/// Thus 10 MiB plus less than 2 KiB of intent/receipt framing fits in this 12 MiB cap.
/// Per-record caps are checked BEFORE the intent is written; the shared recovery read cap
/// remains the existing larger batch cap, followed by this tighter schema-specific cap.
const MAX_VISIT_INTENT_BYTES: u64 = 12 * 1024 * 1024;

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct VisitIntent {
    operation: FieldVisitOperation,
    account: AccountId,
    game: GameId,
    /// Only storage's envelope schema is stamped. Keep the caller's original value to
    /// reconstruct and verify the complete request digest during crash recovery.
    requested_character_schema: u32,
    request: String,
    before: Images,
    after: Images,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct VisitIntentFile {
    schema_version: u32,
    kind: String,
    checksum: String,
    intent: VisitIntent,
}

fn request_digest(operation: &FieldVisitOperation, before: &SceneState, after: &SceneState) -> Result<String> {
    digest(&("fmv-field-visit-request-v1", operation, before, after))
}

impl Store {
    /// Commit a validated entry or ready-state change with its opaque story/resource result.
    /// This foundation accepts idle accounts only: no active checkpoint or reservation. Game
    /// semantics, source validation, accepted entry and anchor reconstruction remain the
    /// caller's responsibility. Runtime activation is deliberately separate from storage.
    ///
    /// Both arguments are exact full snapshots. Retrying the identical last operation returns
    /// current state without reapplying anything, even after later rewards. Reusing its id
    /// with any other request conflicts. Older forgotten operations must still pass exact CAS;
    /// revision/entry changes prevent normal old requests from becoming current again.
    /// An explicit trash restore rekeys account ids: it preserves receipt bytes, but an old
    /// request adapted to the new account conflicts. Continue from its current revision with
    /// a new operation id; do not reinterpret an old account's request as a fresh mutation.
    /// A successful first use or duplicate requires index5 before acknowledgment. Validation
    /// failures do not opt a legacy store into the new format. Uncertain I/O requires reopen.
    pub fn commit_field_visit(&self, operation: &FieldVisitOperation, expected: &SceneState, next: &SceneState) -> Result<FieldVisitCommitted> {
        self.commit_field_visit_with_hook(operation, expected, next, |_| Ok(()))
    }

    fn commit_field_visit_with_hook(&self, operation: &FieldVisitOperation, expected: &SceneState, next: &SceneState, mut hook: impl FnMut(u8) -> Result<()>) -> Result<FieldVisitCommitted> {
        validate_transition(operation, expected, next)?;
        let request = request_digest(operation, expected, next)?;
        let (account, game) = (expected.pair.story.account_id, expected.pair.story.game);
        let writer = self.writer()?;
        let _progress = self.progress_write();
        if !self.index().contains_account(account.0) { return Err(PersistError::UnknownAccount(account)); }
        let before = self.read_images(account, game)?;
        let record = before.character.as_ref().ok_or_else(|| invalid("character progress is absent"))?;
        if record.has_continuation() { return Err(conflict("account has an active scene continuation")); }
        if let Some(receipt) = record.last_visit_commit.as_ref().filter(|receipt| receipt.operation == operation.id) {
            if receipt.request != request { return Err(conflict("visit operation already has a different exact request")); }
            self.ensure_field_visit_format(&writer)?;
            return Ok(FieldVisitCommitted { commit: SceneCommit::AlreadyApplied, current: before.state(account, game) });
        }
        if before.state(account, game) != *expected { return Err(conflict("visit, story, resources or continuation precondition changed")); }
        let requested_character = next.pair.character.as_ref().ok_or_else(|| invalid("character after-image is absent"))?;
        let mut character = record.clone();
        character.progress = requested_character.clone();
        character.field_visit = next.field_visit.clone();
        character.last_visit_commit = Some(VisitReceipt { operation: operation.id, request: request.clone() });
        character.stamp();
        character.validate()?;
        let intent = VisitIntent { operation: *operation, account, game, request,
            requested_character_schema: requested_character.schema_version,
            before, after: Images { story: Some(next.pair.story.clone()), character: Some(character) } };
        self.validate_visit_intent(&intent)?;
        self.encode_visit_images(&intent.before, account, game)?;
        self.encode_visit_images(&intent.after, account, game)?;
        let file = VisitIntentFile { schema_version: VISIT_INTENT_VERSION, kind: "fmv-field-visit-transaction".into(), checksum: digest(&intent)?, intent };
        let path = self.root.join(INTENT_FILE);
        let mut bytes = serde_json::to_vec(&file).map_err(|e| invalid(&format!("cannot encode visit intent: {e}")))?;
        bytes.push(b'\n');
        if bytes.len() as u64 > MAX_VISIT_INTENT_BYTES { return Err(PersistError::TooLarge { path, size: bytes.len() as u64, max: MAX_VISIT_INTENT_BYTES }); }
        hook(0)?;
        self.ensure_field_visit_format(&writer)?;
        self.transaction_poisoned.store(true, Ordering::Release);
        fsio::atomic_write(&path, &bytes)?;
        hook(1)?;
        self.install_visit_after(&file.intent, &mut hook)?;
        std::fs::remove_file(&path).map_err(|e| PersistError::io("remove visit intent", &path, e))?;
        hook(4)?;
        fsio::sync_dir(&self.root).map_err(|e| PersistError::io("sync visit intent removal", &self.root, e))?;
        hook(5)?;
        self.transaction_poisoned.store(false, Ordering::Release);
        Ok(FieldVisitCommitted { commit: SceneCommit::Applied, current: file.intent.after.state(account, game) })
    }

    fn validate_visit_intent(&self, intent: &VisitIntent) -> Result<()> {
        intent.before.pair(intent.account, intent.game).validate(intent.account, intent.game)?;
        intent.after.pair(intent.account, intent.game).validate(intent.account, intent.game)?;
        let before = intent.before.state(intent.account, intent.game);
        let mut requested = intent.after.state(intent.account, intent.game);
        let requested_character = requested.pair.character.as_mut().ok_or_else(|| invalid("missing visit character after-image"))?;
        requested_character.schema_version = intent.requested_character_schema;
        validate_transition(&intent.operation, &before, &requested)?;
        if request_digest(&intent.operation, &before, &requested)? != intent.request { return Err(invalid("visit request digest mismatch")); }
        let old = intent.before.character.as_ref().ok_or_else(|| invalid("missing visit character before-image"))?;
        let new = intent.after.character.as_ref().ok_or_else(|| invalid("missing visit character after-image"))?;
        old.validate()?;
        new.validate()?;
        if intent.after.story.is_none() || old.last_visit_commit.as_ref().is_some_and(|receipt| receipt.operation == intent.operation.id) {
            return Err(invalid("visit intent must append a fresh operation with a story after-image"));
        }
        let receipt = VisitReceipt { operation: intent.operation.id, request: intent.request.clone() };
        receipt.validate()?;
        let mut allowed = old.clone();
        allowed.progress = new.progress.clone();
        allowed.field_visit = new.field_visit.clone();
        allowed.last_visit_commit = Some(receipt);
        if allowed != *new { return Err(invalid("visit intent cannot change other durable metadata")); }
        Ok(())
    }

    fn encode_visit_images(&self, images: &Images, account: AccountId, game: GameId) -> Result<()> {
        if let Some(story) = &images.story { encoded(&self.progression_path(account.0, game)?, story, MAX_RECORD_BYTES)?; }
        if let Some(character) = &images.character { encoded(&self.character_path(account.0, game)?, character, MAX_CHARACTER_RECORD_BYTES)?; }
        Ok(())
    }

    fn install_visit_after(&self, intent: &VisitIntent, hook: &mut impl FnMut(u8) -> Result<()>) -> Result<()> {
        let story = intent.after.story.as_ref().ok_or_else(|| invalid("missing visit story after-image"))?;
        let character = intent.after.character.as_ref().ok_or_else(|| invalid("missing visit character after-image"))?;
        let story_path = self.progression_path(intent.account.0, intent.game)?;
        let character_path = self.character_path(intent.account.0, intent.game)?;
        let story_bytes = encoded(&story_path, story, MAX_RECORD_BYTES)?;
        let character_bytes = encoded(&character_path, character, MAX_CHARACTER_RECORD_BYTES)?;
        fsio::ensure_dir(&self.progression_dir(intent.account.0))?;
        fsio::atomic_write(&story_path, &story_bytes)?;
        hook(2)?;
        fsio::atomic_write(&character_path, &character_bytes)?;
        hook(3)
    }

    pub(super) fn recover_field_visit(&self, path: &Path, bytes: &[u8]) -> Result<()> {
        if bytes.len() as u64 > MAX_VISIT_INTENT_BYTES { return Err(PersistError::TooLarge { path: path.into(), size: bytes.len() as u64, max: MAX_VISIT_INTENT_BYTES }); }
        if self.index().format_version() < crate::index::FIELD_VISIT_INDEX_VERSION {
            return Err(PersistError::corrupt(path, "visit intent lacks its required index format fence"));
        }
        let file: VisitIntentFile = serde_json::from_slice(bytes).map_err(|e| PersistError::corrupt(path, format!("invalid visit intent: {e}")))?;
        if file.schema_version != VISIT_INTENT_VERSION || file.kind != "fmv-field-visit-transaction" || file.checksum != digest(&file.intent)? {
            return Err(PersistError::corrupt(path, "visit intent kind, schema or checksum mismatch"));
        }
        let intent = &file.intent;
        self.validate_visit_intent(intent).map_err(|e| PersistError::corrupt(path, e.to_string()))?;
        self.encode_visit_images(&intent.before, intent.account, intent.game)?;
        self.encode_visit_images(&intent.after, intent.account, intent.game)?;
        if !self.index().contains_account(intent.account.0) { return Err(PersistError::corrupt(path, "visit intent account is not live")); }
        let current = self.read_images(intent.account, intent.game)?;
        if (current.story != intent.before.story && current.story != intent.after.story)
            || (current.character != intent.before.character && current.character != intent.after.character) {
            return Err(PersistError::corrupt(path, "visit intent conflicts with unrelated progress; nothing overwritten"));
        }
        self.install_visit_after(intent, &mut |_| Ok(()))?;
        std::fs::remove_file(path).map_err(|e| PersistError::io("remove recovered visit intent", path, e))?;
        fsio::sync_dir(&self.root).map_err(|e| PersistError::io("sync recovered visit removal", &self.root, e))?;
        Ok(())
    }
}
